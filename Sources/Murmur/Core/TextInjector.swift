import AppKit
import ApplicationServices
import Foundation

/// Puts text into whichever field has keyboard focus.
///
/// Accessibility insertion is tried first; if that cannot be trusted, the transcript goes
/// through the pasteboard with Command-V and the user's clipboard is put back afterwards.
/// Some apps (Electron, Chrome, most terminals) answer the AX write with success and then
/// ignore it, so the return code is not evidence. An AX insert is accepted only when the
/// insertion point is seen to have moved. All of this works because the HUD is a
/// non-activating panel: focus stays in the target app.
@MainActor
enum TextInjector {
    private static var pasteTask: Task<Void, Never>?

    /// The user's clipboard while a restore is still pending, and the pasteboard generation
    /// our transcript was written at. A second paste inside the restore delay reuses these
    /// contents instead of snapshotting the pasteboard, which would capture the *previous
    /// transcript* and restore that in place of what the user had copied.
    private static var pendingRestore: (saved: [[NSPasteboard.PasteboardType: Data]]?, changeCount: Int)?

    /// nspasteboard.org markers. Clipboard managers that honour them neither keep the
    /// transcript in their history (`Transient`) nor show it (`Concealed`); `AutoGenerated`
    /// says no person copied it. The transcript is on the pasteboard for well under a second
    /// and should not outlive that in anyone's clipboard history.
    private static let privacyMarkers: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    /// Whether keyboard focus is in a password field (`AXSecureTextField`).
    ///
    /// Typing a transcript there is almost never intended, and a dictated password would
    /// otherwise land on the pasteboard and in transcription history in plain text.
    static func focusIsSecureField() -> Bool {
        let system = AXUIElementCreateSystemWide()
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(
            system,
            kAXFocusedUIElementAttribute as CFString,
            &focused
        ) == .success, let focused else { return false }

        guard CFGetTypeID(focused) == AXUIElementGetTypeID() else { return false }
        // The type ID was just checked, so the bridge cannot fail.
        let element = focused as! AXUIElement
        var subrole: CFTypeRef?
        guard AXUIElementCopyAttributeValue(
            element,
            kAXSubroleAttribute as CFString,
            &subrole
        ) == .success else { return false }
        return (subrole as? String) == kAXSecureTextFieldSubrole as String
    }

    static func insert(_ text: String) async -> Bool {
        guard !text.isEmpty, !Task.isCancelled else { return false }

        switch insertViaAccessibility(text) {
        case .inserted:
            Log.inject.info("inserted via accessibility (\(text.count) chars)")
            return true
        case .unverified(let reason):
            Log.inject.info("accessibility insert not verified (\(reason, privacy: .public)); falling back to paste")
            return await insertViaPasteboard(text)
        }
    }

    // MARK: - Strategy 1: Accessibility

    private enum AXOutcome {
        case inserted
        case unverified(String)
    }

    /// Writes the text into the focused element's selection and checks that the selection
    /// moved. The check is "did it change at all", not "did it advance by the string length":
    /// falling back after a write that did land would paste the text twice, and apps that
    /// normalize newlines or autocorrect legitimately move the caret by other amounts.
    /// The focused element is fetched on every call and never cached.
    private static func insertViaAccessibility(_ text: String) -> AXOutcome {
        let system = AXUIElementCreateSystemWide()
        var focusedValue: CFTypeRef?
        guard AXUIElementCopyAttributeValue(
            system,
            kAXFocusedUIElementAttribute as CFString,
            &focusedValue
        ) == .success,
              let focusedValue,
              CFGetTypeID(focusedValue) == AXUIElementGetTypeID()
        else { return .unverified("no focused element") }
        let element = focusedValue as! AXUIElement

        var settable: DarwinBoolean = false
        guard AXUIElementIsAttributeSettable(
            element,
            kAXSelectedTextAttribute as CFString,
            &settable
        ) == .success, settable.boolValue else {
            return .unverified("selected text not settable")
        }

        // Without a readable insertion point a real insert cannot be told from a dropped one.
        guard let before = selectedRange(of: element) else {
            return .unverified("selected range unreadable before write")
        }

        guard AXUIElementSetAttributeValue(
            element,
            kAXSelectedTextAttribute as CFString,
            text as CFString
        ) == .success else {
            return .unverified("set attribute failed")
        }

        guard let after = selectedRange(of: element) else {
            return .unverified("range unreadable after write")
        }
        if after.location == before.location, after.length == before.length {
            return .unverified("write accepted but ignored (insertion point stayed at \(before.location))")
        }
        return .inserted
    }

    private static func selectedRange(of element: AXUIElement) -> CFRange? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(
            element,
            kAXSelectedTextRangeAttribute as CFString,
            &value
        ) == .success,
              let value,
              CFGetTypeID(value) == AXValueGetTypeID()
        else { return nil }
        let axValue = value as! AXValue
        var range = CFRange()
        guard AXValueGetType(axValue) == .cfRange,
              AXValueGetValue(axValue, .cfRange, &range)
        else { return nil }
        return range
    }

    // MARK: - Strategy 2: Pasteboard and Command-V

    private static func insertViaPasteboard(_ text: String) async -> Bool {
        let pasteboard = NSPasteboard.general

        // If the previous transcript is still on the pasteboard awaiting its restore, the
        // user's real clipboard is the one that restore holds, not what is on it now.
        let saved: [[NSPasteboard.PasteboardType: Data]]?
        if let pending = pendingRestore, pasteboard.changeCount == pending.changeCount {
            saved = pending.saved
        } else {
            saved = pasteboard.pasteboardItems?.compactMap { item -> [NSPasteboard.PasteboardType: Data] in
                var entry: [NSPasteboard.PasteboardType: Data] = [:]
                for type in item.types {
                    if let data = item.data(forType: type) { entry[type] = data }
                }
                return entry
            }
        }

        // A previous fallback may still be waiting to post ⌘V or restore the clipboard.
        // Cancel it before replacing the pasteboard so an older transcript cannot win the
        // race with the current one.
        pasteTask?.cancel()
        pendingRestore = nil
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for marker in privacyMarkers { item.setData(Data(), forType: marker) }
        guard pasteboard.writeObjects([item]) else {
            Log.inject.error("failed to write transcript to pasteboard")
            restore(saved, to: pasteboard)
            return false
        }

        let expectedChangeCount = pasteboard.changeCount

        // Do not post ⌘V until the pasteboard exposes this exact generation and string.
        // A successful write call alone does not prove that the target can read it yet.
        guard await waitForPasteboard(
            text,
            changeCount: expectedChangeCount,
            pasteboard: pasteboard
        ), !Task.isCancelled, postCommandV() else {
            Log.inject.error("paste event could not be posted for the current transcript")
            if pasteboard.changeCount == expectedChangeCount {
                restore(saved, to: pasteboard)
            }
            return false
        }
        Log.inject.info("paste event posted (\(text.count) chars)")

        pendingRestore = (saved, expectedChangeCount)
        pasteTask = Task { @MainActor in
            // The target app reads the pasteboard asynchronously after the paste event, so wait for it
            // to read the pasteboard. Never overwrite a clipboard value the user changed
            // while the paste was in flight.
            try? await Task.sleep(for: .milliseconds(750))
            guard !Task.isCancelled else { return }
            pendingRestore = nil
            guard pasteboard.changeCount == expectedChangeCount else { return }
            restore(saved, to: pasteboard)
        }
        return true
    }

    private static func waitForPasteboard(
        _ text: String,
        changeCount: Int,
        pasteboard: NSPasteboard
    ) async -> Bool {
        for _ in 0..<40 {
            guard !Task.isCancelled else { return false }
            if pasteboard.changeCount == changeCount,
               pasteboard.string(forType: .string) == text {
                return true
            }
            try? await Task.sleep(for: .milliseconds(10))
        }
        return false
    }

    private static func postCommandV() -> Bool {
        guard let source = CGEventSource(stateID: .privateState) else { return false }
        let vKey: CGKeyCode = 9  // kVK_ANSI_V
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        else { return false }

        // Flags are set explicitly: a finger may still rest on a modifier (the push-to-talk
        // key can be Right Command), and that state must not leak into the paste.
        down.flags = .maskCommand
        up.flags = .maskCommand
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
        return true
    }

    /// Puts the saved clipboard back. Does nothing when there is nothing to restore.
    private static func restore(_ saved: [[NSPasteboard.PasteboardType: Data]]?, to pasteboard: NSPasteboard) {
        guard let saved, !saved.isEmpty else { return }
        pasteboard.clearContents()
        let items = saved.map { entry -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in entry { item.setData(data, forType: type) }
            return item
        }
        _ = pasteboard.writeObjects(items)
    }
}
